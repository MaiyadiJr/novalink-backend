const express = require('express');
const cors = require('cors');
const crypto = require('crypto');
const axios = require('axios');
const https = require('https');

// Load environment variables for local testing (Render injects these automatically)
try { require('dotenv').config(); } catch (e) {}

const app = express();

// Parse raw body for Paystack signature verification
app.use(express.json({
    verify: (req, res, buf) => {
        req.rawBody = buf;
    }
}));

app.use(cors());
app.use(express.static('public'));

// Configuration Settings from Environment Variables
const CONFIG = {
    PORT: process.env.PORT || 3000,
    PAYSTACK_SECRET_KEY: process.env.PAYSTACK_SECRET_KEY || '',
    MIKROTIK_HOST: process.env.MIKROTIK_HOST || 'hmp0bd9vwcq.sn.mynetname.net',
    MIKROTIK_PORT: process.env.MIKROTIK_PORT || 443,
    MIKROTIK_USER: process.env.MIKROTIK_USER || 'admin',
    MIKROTIK_PASS: process.env.MIKROTIK_PASS || 'Nova@1234',
    ADMIN_PIN: process.env.ADMIN_PIN || '5678'
};

const mikrotikProtocol = CONFIG.MIKROTIK_PORT == 80 ? 'http' : 'https';

// Axios client to communicate with MikroTik REST API
const mikrotikClient = axios.create({
    baseURL: `${mikrotikProtocol}://${CONFIG.MIKROTIK_HOST}:${CONFIG.MIKROTIK_PORT}/rest`,
    auth: {
        username: CONFIG.MIKROTIK_USER,
        password: CONFIG.MIKROTIK_PASS
    },
    httpsAgent: new https.Agent({ rejectUnauthorized: false }),
    timeout: 10000
});

// In-Memory store for generated vouchers waiting for frontend polling
const voucherStore = new Map();

// Helper Function: Generate Secure Voucher Codes (e.g. NV-8A3F)
function generateVoucherCode() {
    return 'NV-' + crypto.randomBytes(3).toString('hex').toUpperCase();
}

// MikroTik Profile Map to ensure exact match with RouterOS profiles
const PROFILE_MAP = {
    '1-Hour': '1-Hour-3Mbps',
    '1-Hour-3Mbps': '1-Hour-3Mbps',
    '1-Hour-2Mbps': '1-Hour-3Mbps',
    '24-Hours': '24-Hours-5Mbps',
    '24-Hours-5Mbps': '24-Hours-5Mbps',
    '7-Days': '7-Days-5Mbps',
    '7-Days-5Mbps': '7-Days-5Mbps',
    '1-Month': '1-Month-5Mbps',
    '1-Month-5Mbps': '1-Month-5Mbps',
    'default': 'default'
};

// Helper Function: Add User to MikroTik Hotspot via REST API
async function createMikrotikUser(username, password, profile) {
    const targetProfile = PROFILE_MAP[profile] || profile || 'default';
    try {
        const response = await mikrotikClient.put('/ip/hotspot/user', {
            name: username,
            password: password,
            profile: targetProfile,
            comment: `Generated by NovaLink (${new Date().toISOString().split('T')[0]})`
        });
        return { success: true, data: response.data, profile: targetProfile };
    } catch (error) {
        console.error(`MikroTik API Error with profile "${targetProfile}":`, error.response ? error.response.data : error.message);
        // Fallback to 'default' profile if specific profile failed
        if (targetProfile !== 'default') {
            try {
                console.log(`Retrying user creation with profile "default"...`);
                const retryResponse = await mikrotikClient.put('/ip/hotspot/user', {
                    name: username,
                    password: password,
                    profile: 'default',
                    comment: `Generated by NovaLink Fallback (${new Date().toISOString().split('T')[0]})`
                });
                return { success: true, data: retryResponse.data, profile: 'default' };
            } catch (retryError) {
                console.error('MikroTik Fallback Error:', retryError.response ? retryError.response.data : retryError.message);
                return { success: false, error: retryError.message };
            }
        }
        return { success: false, error: error.message };
    }
}

// -------------------------------------------------------------------
// 1. INITIALIZE PAYMENT ENDPOINT
// -------------------------------------------------------------------
app.post('/api/initialize-payment', async (req, res) => {
    try {
        const { package: pkg, amount, mac } = req.body;

        if (!pkg || !amount) {
            return res.status(400).json({ status: false, error: 'Missing package or amount' });
        }

        const reference = `NV_REF_${Date.now()}_${Math.floor(Math.random() * 1000)}`;

        const paystackResponse = await axios.post(
            'https://api.paystack.co/transaction/initialize',
            {
                amount: amount * 100, // Paystack expects amount in Kobo
                email: `customer_${Date.now()}@novalink.com`,
                reference: reference,
                metadata: {
                    package: pkg,
                    mac: mac || 'N/A'
                }
            },
            {
                headers: {
                    Authorization: `Bearer ${CONFIG.PAYSTACK_SECRET_KEY}`,
                    'Content-Type': 'application/json'
                }
            }
        );

        res.json({
            status: true,
            authorization_url: paystackResponse.data.data.authorization_url,
            reference: reference
        });

    } catch (error) {
        console.error('Payment Init Error:', error.response ? error.response.data : error.message);
        res.status(500).json({ status: false, error: 'Failed to initialize payment gateway.' });
    }
});

// -------------------------------------------------------------------
// 2. PAYSTACK WEBHOOK LISTENER
// -------------------------------------------------------------------
app.post('/webhook/paystack', async (req, res) => {
    try {
        // Validate Paystack HMAC Signature
        const hash = crypto
            .createHmac('sha512', CONFIG.PAYSTACK_SECRET_KEY)
            .update(req.rawBody)
            .digest('hex');

        if (hash !== req.headers['x-paystack-signature']) {
            console.warn('Unauthorized Paystack Webhook attempt!');
            return res.status(401).send('Invalid signature');
        }

        const event = req.body;

        if (event.event === 'charge.success') {
            const data = event.data;
            const reference = data.reference;
            const pkg = data.metadata.package || '1-Hour';

            console.log(`Payment confirmed for reference: ${reference}, Package: ${pkg}`);

            // Generate Voucher Code
            const voucherCode = generateVoucherCode();

            // Push User to MikroTik Router
            const mikrotikRes = await createMikrotikUser(voucherCode, voucherCode, pkg);

            if (mikrotikRes.success) {
                // Save to store so frontend can poll for it
                voucherStore.set(reference, voucherCode);
                console.log(`Successfully created voucher ${voucherCode} on MikroTik.`);
            } else {
                console.error(`Failed to register voucher ${voucherCode} on router.`);
            }
        }

        res.sendStatus(200);
    } catch (error) {
        console.error('Webhook Error:', error.message);
        res.sendStatus(500);
    }
});

// -------------------------------------------------------------------
// 3. GET VOUCHER POLLING ENDPOINT (with Paystack direct verify fallback)
// -------------------------------------------------------------------
app.get('/api/get-voucher', async (req, res) => {
    const reference = req.query.ref;
    if (!reference) {
        return res.status(400).json({ status: 'error', message: 'Missing reference' });
    }

    // 1. Return immediately if webhook already provisioned the voucher
    if (voucherStore.has(reference)) {
        const voucher = voucherStore.get(reference);
        voucherStore.delete(reference); // Clear after retrieval
        return res.json({ status: 'success', voucher: voucher });
    }

    // 2. Direct Paystack Verification Fallback
    try {
        if (CONFIG.PAYSTACK_SECRET_KEY) {
            const verifyRes = await axios.get(
                `https://api.paystack.co/transaction/verify/${encodeURIComponent(reference)}`,
                {
                    headers: { Authorization: `Bearer ${CONFIG.PAYSTACK_SECRET_KEY}` },
                    timeout: 4000
                }
            );

            if (verifyRes.data?.data?.status === 'success') {
                const data = verifyRes.data.data;
                const pkg = data.metadata?.package || '1-Hour-3Mbps';
                const voucherCode = generateVoucherCode();

                console.log(`Direct verification verified payment for ${reference}. Creating router user...`);
                const mikrotikRes = await createMikrotikUser(voucherCode, voucherCode, pkg);

                if (mikrotikRes.success) {
                    console.log(`Successfully provisioned voucher ${voucherCode} for ${reference}`);
                    return res.json({ status: 'success', voucher: voucherCode });
                } else {
                    console.error(`Failed to register voucher ${voucherCode} on router:`, mikrotikRes.error);
                }
            }
        }
    } catch (e) {
        // Ignored during polling while customer is still in checkout
    }

    res.json({ status: 'pending', message: 'Voucher not ready yet.' });
});

// Package price map
const PACKAGE_PRICES = {
    '1-Hour-2Mbps': 100,
    '1-Hour': 100,
    '24-Hours-5Mbps': 500,
    '24-Hours': 500,
    '7-Days-5Mbps': 2500,
    '7-Days': 2500,
    '1-Month': 3000
};

// -------------------------------------------------------------------
// 4. ADMIN: BATCH VOUCHER GENERATION
// -------------------------------------------------------------------
app.post('/api/admin/generate-vouchers', async (req, res) => {
    const { pin, package: pkg, quantity } = req.body;

    if (pin !== CONFIG.ADMIN_PIN) {
        return res.status(401).json({ status: false, success: false, error: 'Unauthorized PIN' });
    }

    const qty = parseInt(quantity) || 1;
    const generatedVouchers = [];

    for (let i = 0; i < qty; i++) {
        const code = generateVoucherCode();
        const response = await createMikrotikUser(code, code, pkg);
        if (response.success) {
            generatedVouchers.push({
                code: code,
                profile: pkg,
                price: PACKAGE_PRICES[pkg] || 100
            });
        }
    }

    if (generatedVouchers.length === 0) {
        return res.status(502).json({
            status: false,
            success: false,
            error: 'Failed to create user on MikroTik router. Check router firewall and REST API status.'
        });
    }

    res.json({
        status: true,
        success: true,
        count: generatedVouchers.length,
        vouchers: generatedVouchers
    });
});

// -------------------------------------------------------------------
// 5. ADMIN: ACTIVE SESSIONS MONITORING
// -------------------------------------------------------------------
app.get('/api/admin/active-users', async (req, res) => {
    const pin = req.query.pin;

    if (pin !== CONFIG.ADMIN_PIN) {
        return res.status(401).json({ status: false, error: 'Unauthorized PIN' });
    }

    try {
        const response = await mikrotikClient.get('/ip/hotspot/active');
        res.json({ status: true, users: response.data });
    } catch (error) {
        console.error('Fetch Active Users Error:', error.message);
        res.status(500).json({ status: false, error: 'Failed to fetch active sessions from router' });
    }
});

// -------------------------------------------------------------------
// 6. ADMIN: VERIFY CUSTOMER PAYMENT BY REFERENCE
// -------------------------------------------------------------------
app.post('/api/admin/verify-payment', async (req, res) => {
    const { pin, reference } = req.body;

    if (pin !== CONFIG.ADMIN_PIN) {
        return res.status(401).json({ status: false, error: 'Unauthorized PIN' });
    }

    if (!reference) {
        return res.status(400).json({ status: false, error: 'Missing reference' });
    }

    try {
        const verifyRes = await axios.get(
            `https://api.paystack.co/transaction/verify/${encodeURIComponent(reference.trim())}`,
            {
                headers: { Authorization: `Bearer ${CONFIG.PAYSTACK_SECRET_KEY}` },
                timeout: 8000
            }
        );

        const data = verifyRes.data?.data;
        if (!data || data.status !== 'success') {
            return res.status(400).json({
                status: false,
                error: `Payment is not confirmed. Status: ${data?.status || 'Not found'}`
            });
        }

        const pkg = data.metadata?.package || '1-Hour-3Mbps';
        const targetProfile = PROFILE_MAP[pkg] || '1-Hour-3Mbps';
        const voucherCode = generateVoucherCode();

        // Attempt router provisioning (non-blocking if router WAN is unreachable)
        const routerRes = await createMikrotikUser(voucherCode, voucherCode, targetProfile);

        res.json({
            status: true,
            success: true,
            reference: data.reference,
            amount: data.amount / 100,
            channel: data.channel,
            paid_at: data.paid_at,
            customer_name: data.authorization?.sender_name || data.customer?.first_name || 'Customer',
            customer_email: data.customer?.email,
            package: pkg,
            profile: targetProfile,
            voucher: voucherCode,
            routerProvisioned: routerRes.success,
            routerError: routerRes.error || null
        });

    } catch (error) {
        console.error('Admin Verify Error:', error.response?.data || error.message);
        res.status(500).json({
            status: false,
            error: error.response?.data?.message || 'Failed to verify transaction with Paystack'
        });
    }
});

