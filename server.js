// MIKROTIK ROUTER PULL SYNC (.RSC)
// -------------------------------------------------------------------
app.get('/api/router-sync.rsc', (req, res) => {
    const pin = req.query.pin;
    if (pin !== CONFIG.ADMIN_PIN) {
        return res.status(401).send('# Unauthorized PIN\r\n');
    }

    if (pendingRouterUsers.length === 0 && pendingRouterCommands.length === 0) {
        res.setHeader('Content-Type', 'text/plain');
        return res.send('# NovaLink: No pending users\r\n');
    }

    let script = '# NovaLink Hotspot Auto-Sync Script\r\n';
    
    // 1. Execute any pending disconnects or revocations
    while (pendingRouterCommands.length > 0) {
        const cmd = pendingRouterCommands.shift();
        script += `${cmd}\r\n`;
    }

    // 2. Add new users with enforced limit-uptime and profile
    const count = pendingRouterUsers.length;
    while (pendingRouterUsers.length > 0) {
        const u = pendingRouterUsers.shift();
        script += `:do { /ip hotspot user add name="${u.code}" password="${u.code}" profile="${u.profile}" limit-uptime="${u.limitUptime}" comment="NovaLink Sync Ref: ${u.reference}" } on-error={}\r\n`;
    }

    console.log(`[SYNC] Dispatched ${count} user additions & commands to MikroTik router.`);
    res.setHeader('Content-Type', 'text/plain');
    res.send(script);
});

